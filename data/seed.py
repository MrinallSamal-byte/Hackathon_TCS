def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default="data/menu_data.json")
    ap.add_argument("--validate", action="store_true", help="strict-validate after write")
    args = ap.parse_args()

    items = build_items()
    out = Path(args.out)
    # Support running from repo root or elsewhere.
    if not out.is_absolute():
        # Resolve relative to repo root (parent of data/).
        repo_root = Path(__file__).resolve().parents[1]
        out = repo_root / args.out
    out.parent.mkdir(parents=True, exist_ok=True)
    payload = [i.model_dump() for i in items]
    out.write_text(json.dumps(payload, indent=2, ensure_ascii=False), encoding="utf-8")

    n_combo = sum(1 for i in items if i.is_combo)
    n_off = sum(1 for i in items if not i.availability)
    cats = sorted({i.category.value for i in items})
    cuis = sorted({i.cuisine.value for i in items})
    print(f"Wrote {len(items)} items -> {out}")
    print(f"Combos: {n_combo} | Unavailable: {n_off}")
    print(f"Categories: {cats}")
    print(f"Cuisines: {cuis}")
    print(f"Price range: Rs {min(i.price for i in items):.0f}-Rs {max(i.price for i in items):.0f}")
    print(f"Prep range: {min(i.prep_time_minutes for i in items)}-{max(i.prep_time_minutes for i in items)} min")

    if args.validate:
        raw = json.loads(out.read_text(encoding="utf-8"))
        assert 40 <= len(raw) <= 60, "Seed must produce 40-60 items"
        assert sum(1 for r in raw if r["is_combo"]) >= 5, "Need >=5 combos"
        assert sum(1 for r in raw if not r["availability"]) >= 5, "Need >=5 unavailable"
        for r in raw:
            MenuItem(**r)
        print("Validation OK.")


if __name__ == "__main__":
    main()
